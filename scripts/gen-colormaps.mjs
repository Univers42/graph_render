#!/usr/bin/env node
// Generates packages/graph-render/src/colour/tables.ts from the pinned matplotlib
// table. The table data is never typed by hand; run this whenever the digest below
// is updated.
//
//   node scripts/gen-colormaps.mjs            # write the file
//   node scripts/gen-colormaps.mjs --check    # exit 1 when the file is stale
//   node scripts/gen-colormaps.mjs --ref P    # read the table from elsewhere
//
// Exit codes: 0 written or identical, 1 stale under --check, 2 reference missing
// or carrying another digest.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const DIGEST = "ddad3698f5129ceb1792a445371286c08bc9080298e657b3054aea19c9659ef9";
const DEFAULT_REF = "/refs/matplotlib-3.10.0/_cm_listed.py";
const OUTPUT = "packages/graph-render/src/colour/tables.ts";
// Blender's ColorRamp accepts 32 stops at most, and SciGraphs asks for exactly that.
const STOPS = 32;
const ROWS = 256;
const MAPS = ["inferno", "viridis", "plasma", "cividis", "magma", "turbo"];

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(2);
}

function parseArgs(argv) {
  let ref = DEFAULT_REF;
  let check = false;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") check = true;
    else if (arg === "--ref") {
      ref = argv[i + 1] ?? fail("--ref needs a path");
      i += 1;
    } else fail(`unknown argument ${arg}`);
  }
  return { ref, check };
}

/** The rows of `_<name>_data`, keeping each channel's decimal text verbatim. */
function rowsOf(text, name) {
  const start = text.indexOf(`_${name}_data = [`);
  if (start < 0) fail(`reference has no _${name}_data`);
  // The last row closes the outer list on its own line, so the block ends where
  // the next top-level table name begins.
  const end = text.indexOf("\n_", start + 1);
  if (end < 0) fail(`_${name}_data is not followed by another table`);
  const block = text.slice(start, end);
  const rows = [...block.matchAll(/\[([^\][]*)\]/g)].map((m) => m[1]);
  if (rows.length !== ROWS) fail(`_${name}_data has ${rows.length} rows, expected ${ROWS}`);
  return rows.map((row, at) => {
    const parts = row.split(",").map((part) => part.trim());
    if (parts.length !== 3 || parts.some((part) => !/^[0-9.eE+-]+$/.test(part))) {
      fail(`_${name}_data row ${at} is not three floats: ${row}`);
    }
    return parts;
  });
}

/** matplotlib's Colormap.__call__ for a float in [0, 1]. */
function indexAt(k) {
  const scaled = (k / (STOPS - 1)) * ROWS;
  const index = Math.trunc(scaled);
  return index >= ROWS ? ROWS - 1 : index;
}

function renderTable(rows) {
  const maps = MAPS.map((name) => {
    const lines = [];
    for (let k = 0; k < STOPS; k += 1) lines.push(`    ${rows[name][indexAt(k)].join(", ")},`);
    return `  ${name}: [\n${lines.join("\n")}\n  ],`;
  });
  return [
    "/**",
    "// Generated by scripts/gen-colormaps.mjs from the pinned matplotlib table.",
    "//   file:   matplotlib-3.10.0/_cm_listed.py",
    `//   sha256: ${DIGEST}`,
    "// Do not edit: run `node scripts/gen-colormaps.mjs` instead.",
    "//",
    "// 32 stops per map (Blender's ColorRamp limit, SciGraphs/ui/coloring/functions.py:39),",
    "// sampled at x_k = k/31 the way matplotlib indexes a float (SciGraphs/core/",
    "// scigraphs_core/coloring/colormaps.py:329-335 samples the same ramp).",
    "*/",
    `export const COLORMAP_NAMES = [${MAPS.map((n) => `"${n}"`).join(", ")}] as const;`,
    "",
    "export type ColormapName = (typeof COLORMAP_NAMES)[number];",
    "",
    "/** Flat r,g,b triples, 96 numbers per map. */",
    "export const COLORMAP_STOPS: Readonly<Record<ColormapName, readonly number[]>> = {",
    maps.join("\n"),
    "};",
    "",
  ].join("\n");
}

function main() {
  const { ref, check } = parseArgs(process.argv.slice(2));
  let raw;
  try {
    raw = readFileSync(ref);
  } catch {
    fail(`reference not readable: ${ref}`);
  }
  const digest = createHash("sha256").update(raw).digest("hex");
  if (digest !== DIGEST) fail(`reference ${ref} has digest ${digest}, expected ${DIGEST}`);

  const text = raw.toString("utf8");
  const rows = {};
  for (const name of MAPS) rows[name] = rowsOf(text, name);
  const generated = renderTable(rows);

  const here = path.dirname(fileURLToPath(import.meta.url));
  const target = path.join(here, "..", OUTPUT);
  if (check) {
    let committed = "";
    try {
      committed = readFileSync(target, "utf8");
    } catch {
      fail(`${OUTPUT} is missing`);
    }
    if (committed !== generated) {
      process.stderr.write(`${OUTPUT} differs from the pinned reference; regenerate it\n`);
      process.exit(1);
    }
    process.stdout.write(`${OUTPUT} matches the pinned reference\n`);
    return;
  }
  writeFileSync(target, generated);
  process.stdout.write(`wrote ${OUTPUT} from ${ref}\n`);
}

main();
