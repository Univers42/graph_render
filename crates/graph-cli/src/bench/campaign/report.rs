//! The campaign's written output: the per-layout bench table and the three-arm crossover
//! table, plus the `--out` plumbing that writes them.
//!
//! Every table states its own honesty in its own header — medians over the stated repeat
//! count, the two memory halves never summed, the tick derived rather than measured, the
//! machine class it ran on — because a benchmark table that has to be read next to a
//! disclaimer somewhere else is a table that will be read without it.

use super::arms::{self, ArmReading};
use super::{COLUMN_TABLE_B, Sample, ladder, largest_fitting, refused};
use crate::bench::Plan;
use std::path::Path;

/// The campaign's markdown: every row, both memory halves, and the ceiling labels.
pub fn markdown(plan: &Plan, rows: &[(&'static str, Vec<Sample>)], budget_ms: f64) -> String {
    let mut out = String::from(
        "# Phase 9 bench — native arm\n\n\
         Generated by `graph-cli bench --repeat` (prompts/phase-09-scale-bench.md §6). \
         Medians over the stated repeat count; a single timing is noise. `run ms` is the \
         one-shot layout run and `tick ms` is `run / 112` (d3 `alphaDecay(0.06)` to \
         `alphaMin` 0.001) — the ABI has no per-tick entry point, so the tick is derived, \
         and the two harness arms divide the same way. Memory is columns and arena \
         **separately** — the arena is data-dependent and unbounded, so one total would \
         hide which half grew. A size past a registered `scale_ceiling` is refused and \
         listed under its table; `--past-ceiling` runs it, labelled.\n\n",
    );
    out += &format!(
        "seed {} · repeat {} · budget {budget_ms} ms · native, one machine class\n\n",
        plan.seed, plan.repeat
    );
    out += &bench_tables(plan, rows);
    out
}

/// The label a row past its registered `scale_ceiling` carries, so no row reads as if it
/// were inside the ceiling.
fn past(past_ceiling: bool) -> &'static str {
    if past_ceiling { " (past ceiling)" } else { "" }
}

/// The line naming the sizes `plan` asked of `id` that the campaign refused, or nothing.
fn refusal_line(plan: &Plan, id: &str) -> String {
    let Some(entry) = graph_core::registry::find(id) else {
        return String::new();
    };
    let sizes: Vec<u32> = plan
        .sizes
        .iter()
        .copied()
        .filter(|&n| refused(plan, entry, n))
        .collect();
    if sizes.is_empty() {
        return String::new();
    }
    let ceiling = entry.meta.scale_ceiling;
    format!(
        "refused n={sizes:?}: past its scale_ceiling of {ceiling}, not run (`--past-ceiling` runs them)\n"
    )
}

/// One table per layout, plus the columns/node line each is read against.
fn bench_tables(plan: &Plan, rows: &[(&'static str, Vec<Sample>)]) -> String {
    let mut out = String::new();
    for (id, samples) in rows {
        out += &format!("## {id}\n\n");
        out += "| n | edges | build ms | run ms | tick ms | settle ms | columns B | arena B | bin B | json B |\n";
        out += "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n";
        for s in samples {
            out += &format!(
                "| {}{} | {} | {:.2} | {:.3} | {:.3} | {:.1} | {} | {} | {} | {} |\n",
                s.n,
                past(s.past_ceiling),
                s.edges,
                s.build_ms,
                s.run_ms,
                s.tick_ms(),
                super::settle_ms(s.tick_ms()),
                s.columns,
                s.arena,
                s.bin,
                s.json
            );
        }
        let per_node: Vec<f64> = samples.iter().map(Sample::columns_per_node).collect();
        out += &format!(
            "\ncolumns/node {per_node:?} against the {COLUMN_TABLE_B} B/node table (`prompt.md` §5.1)\n\n"
        );
        out += &refusal_line(plan, id);
    }
    out
}

/// The crossover: the largest `N` whose tick still fits the budget, per arm — the
/// project's justification stated in the units the premise was stated in.
pub fn crossover_markdown(plan: &Plan, budget_ms: f64) -> String {
    let native = ladder(plan);
    let mut readings = vec![ArmReading::measured(
        "native (graph-core, this process)",
        largest_fitting(&native, budget_ms),
        &native,
    )];
    readings.extend(arms::other_arms());
    let mut out = String::from(
        "# Phase 9 crossover — largest N per arm that fits the frame budget\n\n\
         The headline deliverable is this table, not a pass or fail. Rust faster than the \
         TypeScript oracle at no N would be a stop-and-ask; WASM losing at N = 220 is a \
         row, not a verdict. Every arm's tick is `run / 112` for the same reason and the \
         same way: the motor settles a layout in one call and has no per-tick entry point.\n\n",
    );
    out += &arms::arms_markdown(&readings, budget_ms);
    out.push_str(
        "\nMachine class: whatever `graph-cli bench` and the two Node harnesses ran on. Not \
         portable: the harness is a sampler of one machine, one seed, one reference degree. \
         A size past the largest measured is an extrapolation, not a number.\n",
    );
    out
}

/// The campaign's entry point: measure, print a row per cell, and write the report the
/// plan asks for. `true` unless a run inside its ceiling failed.
pub fn report(plan: &Plan) -> Result<bool, String> {
    if plan.crossover {
        return report_crossover(plan);
    }
    let rows = super::run(plan)?;
    for (id, samples) in &rows {
        let refusal = refusal_line(plan, id);
        if !refusal.is_empty() {
            print!("{id} {refusal}");
        }
        for s in samples {
            println!(
                "{id} n={}{} build {:.2} ms  run {:.3} ms  tick {:.3} ms  settle {:.1} ms  columns {}  arena {}  bin {}  json {}",
                s.n,
                past(s.past_ceiling),
                s.build_ms,
                s.run_ms,
                s.tick_ms(),
                s.settle_ms(),
                s.columns,
                s.arena,
                s.bin,
                s.json
            );
        }
    }
    if let Some(path) = &plan.out {
        write_report(path, &markdown(plan, &rows, plan.budget_ms))?;
    }
    Ok(true)
}

/// `--crossover`: the largest N per arm, to `--out` or to standard output.
fn report_crossover(plan: &Plan) -> Result<bool, String> {
    let text = crossover_markdown(plan, plan.budget_ms);
    match &plan.out {
        Some(path) => write_report(path, &text).map(|()| true),
        None => {
            print!("{text}");
            Ok(true)
        }
    }
}

/// Writes `text` to `path`, or returns the refusal.
pub fn write_report(path: &Path, text: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}
